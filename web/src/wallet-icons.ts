/** The SVG path of an icon: one rectangle per run of lit pixels. Empty for a name that is not an icon. */
export function iconPath(icon: string): string {
  const rows = ICON_BITMAPS[icon];
  if (!rows) return '';
  let path = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === '#') end += 1;
      path += `M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end;
    }
  });
  return path;
}

/** An icon as an SVG image. The caller supplies the pixel mark for `auto` and for anything unknown. */
export function iconSvg(icon: string, label: string, fallback: string): string {
  const path = iconPath(icon);
  if (!path) return fallback;
  const safe = label.replace(/[&<>"']/g, '');
  return `<svg viewBox="-1 -1 ${ICON_SIZE + 2} ${ICON_SIZE + 2}" role="img" aria-label="${safe} icon" shape-rendering="crispEdges"><rect x="-1" y="-1" width="${ICON_SIZE + 2}" height="${ICON_SIZE + 2}" class="avatar-bg"/><path d="${path}"/></svg>`;
}
